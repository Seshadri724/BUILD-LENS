// Package triage turns a finding into reviewer-facing context: what happened,
// the evidence, and the suggested fix. Evidence only — package identity,
// paths, destinations, byte counts, timings. It never prints file contents,
// payloads or secret values: cmdline is deliberately ignored (tokens
// frequently appear in argv) and only metadata fields are rendered.
package triage

import (
	"fmt"
	"slices"
	"strings"

	"github.com/buildlens/buildlens/pkg/runschema"
)

// PromptInjectionAdvice is the response guidance for findings produced through
// an AI coding agent. Single source of truth: the sarif package reuses it for
// step summaries and SARIF messages.
const PromptInjectionAdvice = "Rotate the secret. Then read the issue, PR comment or file the agent was working from for instructions it shouldn't have followed (prompt injection), and limit what the agent's job can reach: `permissions:`, the secrets passed to it, and its allowed tools."

// credentialTiers are file tiers where the file itself is the secret: assume
// exposure and rotate, even when byte volume is unknown.
var credentialTiers = []string{
	"env", "runner_env", "cloud_credential", "git_credential",
	"package_token", "ssh_key", "process_memory", "system_auth",
}

// Render returns a markdown evidence-chain narrative for one finding. It is
// labeled as auto-generated by the caller: raw evidence always stays primary,
// this never stands alone as the verdict.
func Render(f runschema.Finding) string {
	var sb strings.Builder
	sb.WriteString("**Suggested context** (auto-generated — verify against the evidence above):\n\n")

	pkg := f.Aggregatable.Package
	pkgDisplay := pkg.Name
	if pkg.Version != "" {
		pkgDisplay += "@" + pkg.Version
	}
	if pkgDisplay == "" {
		pkgDisplay = "unknown"
	}

	chain := strings.Join(f.Context.ProcessChain, " → ")
	if chain == "" {
		chain = f.Context.Comm
	}

	switch f.Rule {
	case "TAINTED_EGRESS":
		fmt.Fprintf(&sb, "- **What happened:** `%s` — this process read a `%s` file and then sent data somewhere unexpected.\n", f.Rule, tierName(f.Aggregatable.FileTier))
	case "PROCESS_MEMORY_READ":
		fmt.Fprintf(&sb, "- **What happened:** `%s` — this process read another process's memory or environment; secrets can leave via logs, not just egress.\n", f.Rule)
	case "INSTALL_SCRIPT_EGRESS":
		fmt.Fprintf(&sb, "- **What happened:** `%s` — this dependency's install script contacted a host outside the registry allowlist.\n", f.Rule)
	default:
		fmt.Fprintf(&sb, "- **What happened:** `%s` (%s).\n", f.Rule, f.Severity)
	}

	eco := pkg.Ecosystem
	if eco == "" {
		eco = "unknown"
	}
	conf := f.Context.Attribution.Confidence
	if conf == "" {
		conf = "unknown"
	}
	life := f.Context.Attribution.Lifecycle
	if life == "" {
		life = "unknown"
	}
	fmt.Fprintf(&sb, "- **Package:** `%s` (%s, confidence `%s`, lifecycle `%s`)\n", pkgDisplay, eco, conf, life)
	fmt.Fprintf(&sb, "- **Chain:** `%s`\n", chain)
	if f.Context.Path != "" {
		if tier := f.Aggregatable.FileTier; tier != "" {
			fmt.Fprintf(&sb, "- **File:** `%s` (tier `%s`)\n", f.Context.Path, tier)
		} else {
			fmt.Fprintf(&sb, "- **File:** `%s`\n", f.Context.Path)
		}
	}
	if f.Aggregatable.DestHost != "" {
		if raw := f.Context.Dest; raw != "" && !strings.Contains(raw, f.Aggregatable.DestHost) {
			fmt.Fprintf(&sb, "- **Destination:** `%s` (raw `%s`)\n", f.Aggregatable.DestHost, raw)
		} else {
			fmt.Fprintf(&sb, "- **Destination:** `%s`\n", f.Aggregatable.DestHost)
		}
	}
	if b := f.Aggregatable.BytesSent; b != nil {
		fmt.Fprintf(&sb, "- **Volume/timing:** `%d bytes sent, %d ms after the read`\n", *b, f.Aggregatable.ElapsedMS)
	} else if f.Aggregatable.ElapsedMS != 0 {
		fmt.Fprintf(&sb, "- **Volume/timing:** `byte volume not measured, %d ms after the read`\n", f.Aggregatable.ElapsedMS)
	}
	if f.Context.Agent != "" {
		fmt.Fprintf(&sb, "- **Via AI agent:** `%s`\n", f.Context.Agent)
	}
	if f.Context.Cwd != "" {
		fmt.Fprintf(&sb, "- **Working dir:** `%s`\n", f.Context.Cwd)
	}
	if f.Context.Fingerprint != "" {
		sb.WriteString("- **Finding ID:** `" + f.Context.Fingerprint + "` (matches SARIF `partialFingerprints.buildlens/v1`)\n")
	}

	sb.WriteString("- **Suggested fix:**\n")
	sb.WriteString(fixBlock(f))
	return sb.String()
}

func fixBlock(f runschema.Finding) string {
	var sb strings.Builder
	pkg := f.Aggregatable.Package
	agentInvolved := f.Context.Agent != "" || pkg.Ecosystem == "agent"
	if agentInvolved {
		sb.WriteString("  " + PromptInjectionAdvice + "\n")
	}
	switch {
	case pkg.Ecosystem == "agent":
		// The agent itself is blamed; there is no dependency to remove.
		if f.Context.Agent == "" {
			sb.WriteString("  Review the agent's run: commands, files and hosts are listed above.\n")
		}
	case pkg.IsUnknown():
		sb.WriteString("  Identify the responsible dependency from the process chain above, then remove or pin it.\n")
	default:
		fmt.Fprintf(&sb, "  ```bash\n  npm uninstall %s && npm install --package-lock-only\n  ```\n", pkg.Name)
	}
	if slices.Contains(credentialTiers, f.Aggregatable.FileTier) || f.Rule == "PROCESS_MEMORY_READ" {
		sb.WriteString("  Rotate the exposed secret: it was readable at read time — assume it left.\n")
	}
	return sb.String()
}

func tierName(tier string) string {
	if tier == "" {
		return "sensitive"
	}
	return tier
}
